EXPECTED_BARS = 744
FIRST_TS = 1767225600  # 2026-01-01 00:00:00 UTC
LAST_TS = 1769900400   # 2026-01-31 23:00:00 UTC


def build() -> dict:
    closes: list[float] = []
    timestamps: list[int] = []

    for period1, period2, raw in WINDOWS:
        cleaned = [c for c in raw if c is not None]
        # Yahoo returns exactly one trailing boundary bar with close=null.
        if len(cleaned) != len(raw) - 1:
            raise ValueError(
                f"window {period1}-{period2}: expected exactly 1 trailing null, "
                f"got {len(raw) - len(cleaned)}"
            )
        expected = (period2 - period1) // 3600
        if len(cleaned) != expected:
            raise ValueError(
                f"window {period1}-{period2}: expected {expected} bars, got {len(cleaned)}"
            )
        closes.extend(cleaned)
        timestamps.extend(period1 + 3600 * i for i in range(expected))

    if len(closes) != EXPECTED_BARS:
        raise ValueError(f"expected {EXPECTED_BARS} closes, got {len(closes)}")
    if timestamps[0] != FIRST_TS or timestamps[-1] != LAST_TS:
        raise ValueError(f"timestamp span wrong: {timestamps[0]}..{timestamps[-1]}")
    if sorted(set(timestamps)) != timestamps:
        raise ValueError("timestamps are not strictly increasing / contain duplicates")

    return {
        "symbol": "BTC-USD",
        "interval": "1h",
        "source": "Yahoo Finance Chart API v8",
        "source_url": (
            "https://query1.finance.yahoo.com/v8/finance/chart/BTC-USD"
            "?period1=1767225600&period2=1769817600&interval=1h"
        ),
        "retrieval_note": (
            "Full-month request paginates into 13 chunks; retrieved here as ten "
            "3-day windows plus one 1-day window, each a single clean JSON payload. "
            "The trailing boundary bar (close=null) is dropped from every window."
        ),
        "period_start_utc": datetime.fromtimestamp(FIRST_TS, timezone.utc).isoformat(),
        "period_end_utc": datetime.fromtimestamp(LAST_TS, timezone.utc).isoformat(),
        "bars": len(closes),
        "windows": len(WINDOWS),
        "timestamps": timestamps,
        "closes": closes,
    }


